// Builds functions/_lib/catalog.js from the site's own data files, so the
// server checks prices, delivery fees and dates against exactly what the site shows.
// Runs automatically on every Cloudflare deploy (build command: node tools/build-catalog.mjs).
import fs from "node:fs";
import vm from "node:vm";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const sandbox = { window: {} };
vm.createContext(sandbox);
for (const f of ["config.js", "extras.js", "delivery-zones.js", "product-options.js"]) {
  vm.runInContext(fs.readFileSync(path.join(root, f), "utf8"), sandbox, { filename: f });
}
const W = sandbox.window;

const products = {};
for (const f of fs.readdirSync(path.join(root, "products")).filter((f) => f.endsWith(".html"))) {
  const html = fs.readFileSync(path.join(root, "products", f), "utf8");
  const m = html.match(/data-add='(\{[^']*\})'/);
  if (!m) continue;
  const d = JSON.parse(m[1].replace(/&#39;/g, "'").replace(/&quot;/g, '"').replace(/&amp;/g, "&"));
  const po = W.PRODUCT_OPTIONS[d.id];
  if (po && po.base !== d.price) throw new Error(`${d.id}: page price ${d.price} but product-options.js base ${po.base}`);
  products[d.id] = { name: d.name, price: d.price, img: d.img, options: po ? po.options : [] };
}
if (Object.keys(products).length < 10) throw new Error("Too few products found");

const catalog = {
  products,
  extras: W.EXTRAS,
  zones: W.DELIVERY_ZONES.map((z) => ({ id: z.id, name: z.name, type: z.type, fee: +z.fee || 0, sameDay: z.sameDay !== false, cutoffHour: z.cutoffHour || W.SITE.cutoffHour || 14, suburbs: z.suburbs || [], areas: z.areas || [] })),
  unknownName: (W.DELIVERY_UNKNOWN || {}).name || "Outside our listed areas",
  closedDates: W.SITE.closedDates || [],
  cutoffHour: W.SITE.cutoffHour || 14,
  phone: W.SITE.phone,
};
fs.writeFileSync(
  path.join(root, "functions/_lib/catalog.js"),
  "// GENERATED by tools/build-catalog.mjs. Don't edit: change the site's data files instead.\nexport default " + JSON.stringify(catalog) + ";\n"
);
console.log(`catalog: ${Object.keys(products).length} products, ${catalog.extras.length} extras, ${catalog.zones.length} zones`);
